#!/usr/bin/env python3
"""Install or repair the singularity diagnostics in the Project repository.

Run from the repository root:
    python3 singularity_diagnostics_update/apply_singularity_diagnostics.py

This script is safe to rerun. It backs up src/Isosurface.h once, installs the
standalone test, and rewrites the complete emitTri lambda as a unit. Replacing
the whole lambda avoids brittle edits to the inline degenerate-area guard and
repairs the malformed `}, skip` code emitted by earlier versions of the patch.
"""
from pathlib import Path
import shutil
import sys

ROOT = Path.cwd()
HERE = Path(__file__).resolve().parent
HEADER = ROOT / "src" / "Isosurface.h"
CMAKE = ROOT / "CMakeLists.txt"
TEST_DIR = ROOT / "tests"
TEST_DEST = TEST_DIR / "test_singularity_diagnostics.cpp"


def fail(message: str) -> None:
    print(f"ERROR: {message}", file=sys.stderr)
    raise SystemExit(1)


if not CMAKE.is_file() or not HEADER.is_file():
    fail("Run from the repository root (expected CMakeLists.txt and src/Isosurface.h).")

TEST_DIR.mkdir(parents=True, exist_ok=True)
shutil.copy2(HERE / "tests" / "test_singularity_diagnostics.cpp", TEST_DEST)
shutil.copy2(HERE / "tests" / "SINGULARITY_DIAGNOSTICS.md", TEST_DIR / "SINGULARITY_DIAGNOSTICS.md")

h = HEADER.read_text(encoding="utf-8")
original_h = h

# Explicitly include the standard declarations used by the instrumentation.
if "#include <cstddef>" not in h:
    include_anchor = "#include <vector>"
    if include_anchor not in h:
        fail("Could not find #include <vector> in src/Isosurface.h.")
    h = h.replace(include_anchor, include_anchor + "\n#include <cstddef>", 1)

# Define coordinates before IsosurfaceResult.
geometry_type = """struct SkippedTriangleGeometry {
    float ax, ay, az, bx, by, bz, cx, cy, cz;
};
"""
if "struct SkippedTriangleGeometry" not in h:
    result_anchor = "struct IsosurfaceResult {"
    if result_anchor not in h:
        fail("Could not find IsosurfaceResult declaration in src/Isosurface.h.")
    h = h.replace(result_anchor, geometry_type + result_anchor, 1)

# Instrumentation fields, inserted idempotently.
if "skippedDegenerateTriangles" not in h:
    max_grad_anchor = "    double maxGradMag = 1e-9; // for color normalization"
    if max_grad_anchor not in h:
        import re
        match = re.search(r"^[ \t]*double maxGradMag\s*=\s*1e-9;[^\n]*$", h, re.MULTILINE)
        if not match:
            fail("Could not find IsosurfaceResult.maxGradMag field in src/Isosurface.h.")
        max_grad_anchor = match.group(0)
    h = h.replace(max_grad_anchor, max_grad_anchor +
                  "\n    std::size_t skippedDegenerateTriangles = 0; // triangles dropped by the degenerate-area guard", 1)

if "skippedDegenerateGeometry" not in h:
    count_anchor = "    std::size_t skippedDegenerateTriangles = 0; // triangles dropped by the degenerate-area guard"
    if count_anchor not in h:
        fail("Could not find skippedDegenerateTriangles field in src/Isosurface.h.")
    h = h.replace(count_anchor, count_anchor +
                  "\n    std::vector<SkippedTriangleGeometry> skippedDegenerateGeometry; // positions of dropped triangle candidates", 1)

# Rewrite the whole emitter body. This intentionally handles both the original
# production header and the malformed emitter generated by the previous patch.
import re
start_match = re.search(
    r"^[ \t]*auto emitTri\s*=\s*\[&\]\s*\(\s*const SurfaceVertex& a\s*,\s*"
    r"const SurfaceVertex& b\s*,\s*const SurfaceVertex& c\s*\)\s*\{",
    h, re.MULTILINE)
if not start_match:
    fail("Could not locate auto emitTri in src/Isosurface.h; header left unchanged.")
start = start_match.start()
end_match = re.search(r"^[ \t]*for \(int i = 0; i < res; i\+\+\) \{", h[start_match.end():], re.MULTILINE)
if not end_match:
    fail("Could not find the grid-cell loop after auto emitTri; header left unchanged.")
end = start_match.end() + end_match.start()

fixed_emitter = """        auto emitTri = [&](const SurfaceVertex& a, const SurfaceVertex& b, const SurfaceVertex& c) {
            // Orient each face to agree with the analytic gradient. Capture
            // degenerate candidate geometry before skipping it, for diagnostics.
            const float ex1 = b.px - a.px, ey1 = b.py - a.py, ez1 = b.pz - a.pz;
            const float ex2 = c.px - a.px, ey2 = c.py - a.py, ez2 = c.pz - a.pz;
            const float fnx = ey1 * ez2 - ez1 * ey2;
            const float fny = ez1 * ex2 - ex1 * ez2;
            const float fnz = ex1 * ey2 - ey1 * ex2;
            const float crossLenSq = fnx * fnx + fny * fny + fnz * fnz;
            if (crossLenSq < degenerateAreaEps * degenerateAreaEps) {
                ++result.skippedDegenerateTriangles;
                result.skippedDegenerateGeometry.push_back({
                    a.px, a.py, a.pz, b.px, b.py, b.pz, c.px, c.py, c.pz
                });
                return; // zero-area sliver, skipped and recorded
            }

            const float gnx = a.nx + b.nx + c.nx;
            const float gny = a.ny + b.ny + c.ny;
            const float gnz = a.nz + b.nz + c.nz;
            const float dot = fnx * gnx + fny * gny + fnz * gnz;
            const float gm = std::max({a.gradMag, b.gradMag, c.gradMag});
            result.maxGradMag = std::max(result.maxGradMag, static_cast<double>(gm));
            if (dot < 0.0f) {
                result.vertices.push_back(a);
                result.vertices.push_back(c);
                result.vertices.push_back(b);
            } else {
                result.vertices.push_back(a);
                result.vertices.push_back(b);
                result.vertices.push_back(c);
            }
        };"""
h = h[:start] + fixed_emitter + "\n" + h[end:]

# Back up the already-modified header before writing a repaired version.
backup = HEADER.with_name("Isosurface.h.before_singularity_diagnostics_fix")
if not backup.exists():
    backup.write_text(original_h, encoding="utf-8")
HEADER.write_text(h, encoding="utf-8")

# Add the diagnostics executable and smoke test if they are not already present.
c = CMAKE.read_text(encoding="utf-8")
if "isosurface_singularity_diagnostics" not in c:
    anchor = "add_test(NAME isosurface_correctness COMMAND isosurface_lab_tests)"
    if anchor not in c:
        fail("Could not find existing isosurface_correctness CTest anchor in CMakeLists.txt.")
    block = anchor + "\n\n# Expanded, headless singularity/grid-phase diagnostics.\n" \
        "add_executable(isosurface_singularity_diagnostics tests/test_singularity_diagnostics.cpp)\n" \
        "target_include_directories(isosurface_singularity_diagnostics PRIVATE src)\n" \
        "add_test(NAME singularity_diagnostics_smoke\n" \
        "    COMMAND isosurface_singularity_diagnostics --quick --resolution 20 --out ${CMAKE_BINARY_DIR}/singularity_diagnostics_smoke_artifacts)"
    CMAKE.write_text(c.replace(anchor, block, 1), encoding="utf-8")

print("Repaired Isosurface::build emitTri lambda and verified diagnostic counters are present.")
print("Backup: src/Isosurface.h.before_singularity_diagnostics_fix")
print("Next: cmake -S . -B build -DCMAKE_BUILD_TYPE=Release")
print("      cmake --build build --target isosurface_singularity_diagnostics")
print("      ctest --test-dir build --output-on-failure -R 'singularity_diagnostics_smoke'")
