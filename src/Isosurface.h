class Isosurface {
public:
    // domainHalfExtent: grid spans [-h,h]^3. res: number of cells per axis.
    static IsosurfaceResult build(const Node* ast, double k, int res, double domainHalfExtent) {
        auto t0 = std::chrono::steady_clock::now();
        IsosurfaceResult result;
        if (res < 2) res = 2;

        const int N = res + 1; // grid points per axis
        const double h = domainHalfExtent;
        const double step = (2.0 * h) / res;

        // Precompute value + analytic gradient at every grid point.
        std::vector<GridSample> grid(size_t(N) * N * N);
        auto idx = [N](int i, int j, int kk) { return (size_t(i) * N + j) * N + kk; };

        Dual3 kd(k, 0, 0, 0);
        for (int i = 0; i < N; i++) {
            double x0 = -h + i * step;
            for (int j = 0; j < N; j++) {
                double y0 = -h + j * step;
                for (int kk = 0; kk < N; kk++) {
                    double z0 = -h + kk * step;
                    Dual3 xd(x0, 1, 0, 0), yd(y0, 0, 1, 0), zd(z0, 0, 0, 1);
                    Dual3 r = evalExpr<Dual3>(ast, xd, yd, zd, kd);
                    GridSample& s = grid[idx(i, j, kk)];
                    s.f = r.v; s.gx = r.dx; s.gy = r.dy; s.gz = r.dz;
                }
            }
        }

        // Exact-zero grid-sample tie-break (deterministic, local-scale).
        // Marching Cubes classifies corners with f < 0, so f == 0 is already
        // classified as outside. However, leaving f exactly zero means several
        // incident cube edges can interpolate to the same grid vertex. The
        // resulting duplicate triangle vertices are later discarded by the
        // degenerate-area guard, which can leave holes in an otherwise closed
        // surface (notably the radius-0.5 sphere at resolution 48).
        //
        // Replace only exact zeros with a small positive tie-break value. This
        // preserves each corner's inside/outside classification while moving
        // crossings on incident edges a tiny, locally scaled fraction into the
        // edge. Updates are collected first so each scale uses the ORIGINAL
        // scalar samples, independent of iteration order. This is a numerical
        // tie-break for grid-aligned zeros, not a change to the analytic field.
        constexpr double zeroTieFraction = 1e-3;
        std::vector<std::pair<std::size_t, double>> exactZeroUpdates;
        for (int i = 0; i < N; ++i) {
            for (int j = 0; j < N; ++j) {
                for (int kk = 0; kk < N; ++kk) {
                    const std::size_t sampleIndex = idx(i, j, kk);
                    if (grid[sampleIndex].f != 0.0) continue;

                    double localScale = 0.0;
                    auto includeNeighborMagnitude = [&](int ni, int nj, int nk) {
                        localScale = std::max(
                            localScale,
                            std::fabs(grid[idx(ni, nj, nk)].f));
                    };
                    if (i > 0)  includeNeighborMagnitude(i - 1, j, kk);
                    if (i < res) includeNeighborMagnitude(i + 1, j, kk);
                    if (j > 0)  includeNeighborMagnitude(i, j - 1, kk);
                    if (j < res) includeNeighborMagnitude(i, j + 1, kk);
                    if (kk > 0) includeNeighborMagnitude(i, j, kk - 1);
                    if (kk < res) includeNeighborMagnitude(i, j, kk + 1);

                    if (localScale > 0.0 && std::isfinite(localScale)) {
                        exactZeroUpdates.emplace_back(
                            sampleIndex, zeroTieFraction * localScale);
                    }
                }
            }
        }
        for (const auto& update : exactZeroUpdates) {
            grid[update.first].f = update.second;
        }

        auto worldPos = [&](int i, int j, int kk) {
            return std::array<double,3>{ -h + i * step, -h + j * step, -h + kk * step };
        };

        // A helper that, given two cube corners (world pos + sample), linearly
        // interpolates the zero-crossing position and then re-evaluates the
        // field there (via AD) for an exact normal/gradient. Re-evaluating
        // (rather than interpolating gx/gy/gz) also means two cube cells that
        // share an edge compute *identical* crossing points and normals for
        // that shared edge -- the interpolation only depends on (pa,sa,pb,sb),
        // which are the same from either cell -- which is what keeps the mesh
        // watertight.
        auto cutEdge = [&](const std::array<double,3>& pa, const GridSample& sa,
                            const std::array<double,3>& pb, const GridSample& sb) {
            double t = sa.f / (sa.f - sb.f); // sa.f and sb.f have opposite signs
            double px = pa[0] + t * (pb[0] - pa[0]);
            double py = pa[1] + t * (pb[1] - pa[1]);
            double pz = pa[2] + t * (pb[2] - pa[2]);
            Dual3 xd(px, 1, 0, 0), yd(py, 0, 1, 0), zd(pz, 0, 0, 1);
            Dual3 r = evalExpr<Dual3>(ast, xd, yd, zd, kd);
            SurfaceVertex v{};
            v.px = (float)px; v.py = (float)py; v.pz = (float)pz;
            double gm = std::sqrt(r.dx*r.dx + r.dy*r.dy + r.dz*r.dz);
            v.gradMag = (float)gm;
            if (gm > 1e-12) { v.nx = (float)(r.dx/gm); v.ny=(float)(r.dy/gm); v.nz=(float)(r.dz/gm); }
            else { v.nx = 0; v.ny = 0; v.nz = 1; }
            return v;
        };

        // Degenerate-edge guard: if a grid vertex lands exactly ON the
        // isosurface (F==0 there, not just near it), that corner's cut
        // ratio t can come out as exactly 0 on more than one of the cube's
        // edges meeting at it. Two differently-labeled edges then produce
        // the *same* position, so a triangle can get two coincident
        // vertices -- a zero-area sliver. This is a textbook degenerate
        // input to marching cubes (happens whenever the field is exactly
        // zero along a whole grid line, e.g. here along x=0,y=0 for the
        // cuspidal family, since a symmetric domain centered at 0 puts a
        // grid line exactly there). Rather than rely on a value epsilon
        // (which underflows back to the same float32 position once the
        // interpolated offset is tinier than a float's precision), reject
        // any triangle whose area comes out at ~0 right before emitting it.
        const float degenerateAreaEps = (float)(step * step) * 1e-8f;
        auto emitTri = [&](const SurfaceVertex& a, const SurfaceVertex& b, const SurfaceVertex& c) {
            // Orient each face to agree with the analytic gradient. Capture
            // degenerate candidate geometry before skipping it, for diagnostics.
            const float ex1 = b.px - a.px, ey1 = b.py - a.py, ez1 = b.pz - a.pz;
            const float ex2 = c.px - a.px, ey2 = c.py - a.py, ez2 = c.pz - a.pz;
            const float fnx = ey1 * ez2 - ez1 * ey2;
            const float fny = ez1 * ex2 - ex1 * ez2;
            const float fnz = ex1 * ey2 - ey1 * ex2;
            const float crossLenSq = fnx * fnx + fny * fny + fnz * fnz;
            if (crossLenSq < degenerateAreaEps * degenerateAreaEps) {
                ++result.skippedDegenerateTriangles;
                result.skippedDegenerateGeometry.push_back({
                    a.px, a.py, a.pz, b.px, b.py, b.pz, c.px, c.py, c.pz
                });
                return; // zero-area sliver, skipped and recorded
            }

            const float gnx = a.nx + b.nx + c.nx;
            const float gny = a.ny + b.ny + c.ny;
            const float gnz = a.nz + b.nz + c.nz;
            const float dot = fnx * gnx + fny * gny + fnz * gnz;
            const float gm = std::max({a.gradMag, b.gradMag, c.gradMag});
            result.maxGradMag = std::max(result.maxGradMag, static_cast<double>(gm));
            if (dot < 0.0f) {
                result.vertices.push_back(a);
                result.vertices.push_back(c);
                result.vertices.push_back(b);
            } else {
                result.vertices.push_back(a);
                result.vertices.push_back(b);
                result.vertices.push_back(c);
            }
        };
        for (int i = 0; i < res; i++) {
            for (int j = 0; j < res; j++) {
                for (int kk = 0; kk < res; kk++) {
                    std::array<double,3> cp[8];
                    const GridSample* cs[8];
                    for (int c = 0; c < 8; c++) {
                        int ci = i + kCubeCornerOffset[c][0];
                        int cj = j + kCubeCornerOffset[c][1];
                        int ck = kk + kCubeCornerOffset[c][2];
                        cp[c] = worldPos(ci, cj, ck);
                        cs[c] = &grid[idx(ci, cj, ck)];
                    }

                    // bit c set <=> corner c is "inside" (F < 0).
                    int cubeindex = 0;
                    for (int c = 0; c < 8; c++) if (cs[c]->f < 0) cubeindex |= (1 << c);
                    if (cubeindex == 0 || cubeindex == 255) continue; // entirely outside / inside

                    // Lazily compute (and cache) the zero-crossing vertex for
                    // each of the cube's 12 edges, only for the edges this
                    // cube cell actually needs.
                    SurfaceVertex edgeVertex[12];
                    bool edgeComputed[12] = { false };
                    auto edgeVertexAt = [&](int e) -> const SurfaceVertex& {
                        if (!edgeComputed[e]) {
                            int ca = kEdgeCorners[e][0], cb = kEdgeCorners[e][1];
                            edgeVertex[e] = cutEdge(cp[ca], *cs[ca], cp[cb], *cs[cb]);
                            edgeComputed[e] = true;
                        }
                        return edgeVertex[e];
                    };

                    const int8_t* tri = kTriTable[cubeindex];
                    for (int t = 0; tri[t] != -1; t += 3) {
                        const SurfaceVertex& v0 = edgeVertexAt(tri[t]);
                        const SurfaceVertex& v1 = edgeVertexAt(tri[t+1]);
                        const SurfaceVertex& v2 = edgeVertexAt(tri[t+2]);
                        emitTri(v0, v1, v2);
                    }
                }
            }
        }

        auto t1 = std::chrono::steady_clock::now();
        result.buildMillis = std::chrono::duration<double, std::milli>(t1 - t0).count();
        return result;
    }
};
