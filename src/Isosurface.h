// Isosurface.h
//
// Extracts the zero level set {F(x,y,z;k) = 0} of a user-supplied scalar
// field on a regular grid using the classic 256-case Marching Cubes
// algorithm (Lorensen & Cline 1987). Each grid cell (cube) has 8 corners;
// the sign of F at each corner (inside/outside) selects one of 256 cases,
// and a precomputed triangle table (kTriTable) says which of the cube's 12
// edges to connect into triangles for that case. This is the textbook
// "marching cubes" algorithm, as opposed to the 6-tetrahedra decomposition
// used previously in this file.
//
// Known trade-off vs. the tetrahedra decomposition: a handful of the 256
// cases are "ambiguous" on a cube face (two diagonally-opposite corners
// inside, the other two outside, on the same face) where the standard
// table's choice of diagonal can, in principle, leave a crack against a
// neighboring cube that resolved the same face the other way. In practice
// this is rare for smooth, well-resolved fields and is not something this
// implementation attempts to resolve (e.g. via asymptotic decider tests);
// it's flagged here because it's the well-known caveat of table-based MC,
// and the watertightness test in tests/test_isosurface.cpp is exactly the
// check that would catch it if it happened on the test fields.
//
// Every generated vertex gets its position from linear interpolation along
// the cut cube edge, but its NORMAL / GRADIENT is obtained by re-evaluating
// the field with Dual3 (exact forward-mode AD) at that exact point -- so
// the gradient you see on the surface is the true analytic gradient of F,
// not a finite-difference or interpolated approximation.
#pragma once
#include "Expr.h"
#include <vector>
